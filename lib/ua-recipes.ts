/** Fill in the Ukrainian text of a recipe that has none — for the seed and for
 *  database rows alike, so the live site is translated before the SQL is run.
 *  A recipe that already has Ukrainian text is returned untouched. */
export function withUaRecipe<
  R extends {
    slug: string;
    title: { ua?: string };
    description: { ua?: string };
    ingredients: { ua?: string[] };
    steps: { ua?: string[] };
    tags: { ua?: string[] };
  },
>(r: R): R {
  const ua = UA_RECIPES[r.slug];
  if (!ua || r.title.ua) return r;
  return {
    ...r,
    title: { ...r.title, ua: ua.title },
    description: { ...r.description, ua: ua.description },
    ingredients: { ...r.ingredients, ua: ua.ingredients },
    steps: { ...r.steps, ua: ua.steps },
    tags: { ...r.tags, ua: ua.tags },
  };
}
