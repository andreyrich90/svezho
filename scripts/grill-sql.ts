// Writes supabase/grill_recipes.sql from lib/grill-recipes.ts: the seven
// database-only grill recipes get real Russian, Ukrainian and a corrected
// English. Same ASCII-only encoding as scripts/ua-sql.ts.
//   npx tsx scripts/grill-sql.ts
import { writeFileSync } from "fs";
import { GRILL_RECIPES } from "../lib/grill-recipes";

const json = (v: unknown) =>
  "$j$" + JSON.stringify(v).replace(/[\u007f-￿]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0")) + "$j$::jsonb";
const lit = (s: string) => "'" + s.replace(/'/g, "''") + "'";

const out: string[] = [
  "-- Russian, Ukrainian and corrected English for the seven grill recipes.",
  "-- Generated by scripts/grill-sql.ts. Safe to run more than once: a row that",
  "-- already has Ukrainian text is left alone.",
  "begin;",
];

for (const [slug, g] of Object.entries(GRILL_RECIPES)) {
  out.push(
    `update recipes set` +
      ` title = ${json(g.title)},` +
      ` description = ${json(g.description)},` +
      ` ingredients = ${json(g.ingredients)},` +
      ` steps = ${json(g.steps)},` +
      ` tags = ${json(g.tags)}` +
      ` where slug = ${lit(slug)} and not (title ? 'ua');`
  );
}

out.push("commit;", "");
writeFileSync("supabase/grill_recipes.sql", out.join("\n"));
console.log(`supabase/grill_recipes.sql: ${out.length - 6} statements`);
