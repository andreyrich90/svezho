// Writes supabase/ua_translations.sql from lib/ua-recipes.ts and
// lib/lifehack-copy.ts, so the database ends up with exactly the text the site
// already shows through withUaRecipe()/withLifehackCopy().
//   npx tsx scripts/ua-sql.ts
// The SQL is ASCII-only (JSON \u escapes inside dollar quotes): it survives a
// browser that translates or re-encodes the page it is pasted from.
import { writeFileSync } from "fs";
import { UA_RECIPES } from "../lib/ua-recipes";
import { LIFEHACK_SUMMARIES, UA_LIFEHACKS } from "../lib/lifehack-copy";

const json = (v: unknown) =>
  "$j$" + JSON.stringify(v).replace(/[\u007f-￿]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0")) + "$j$::jsonb";
const lit = (s: string) => "'" + s.replace(/'/g, "''") + "'";

const out: string[] = [
  "-- Ukrainian text for recipes and lifehacks, longer lifehack summaries.",
  "-- Generated by scripts/ua-sql.ts. Safe to run more than once: only rows",
  "-- still missing Ukrainian text, or with a summary under 200 characters, change.",
  "begin;",
];

for (const [slug, r] of Object.entries(UA_RECIPES)) {
  out.push(
    `update recipes set` +
      ` title = title || ${json({ ua: r.title })},` +
      ` description = description || ${json({ ua: r.description })},` +
      ` ingredients = ingredients || ${json({ ua: r.ingredients })},` +
      ` steps = steps || ${json({ ua: r.steps })},` +
      ` tags = tags || ${json({ ua: r.tags })}` +
      ` where slug = ${lit(slug)} and not (title ? 'ua');`
  );
}

for (const [slug, l] of Object.entries(UA_LIFEHACKS)) {
  out.push(
    `update lifehacks set title = title || ${json({ ua: l.title })}, body = body || ${json({ ua: l.body })}` +
      ` where slug = ${lit(slug)} and not (title ? 'ua');`
  );
}

for (const [slug, s] of Object.entries(LIFEHACK_SUMMARIES)) {
  for (const k of ["ru", "en", "ua"] as const) {
    if (!s[k]) continue;
    out.push(
      `update lifehacks set summary = summary || ${json({ [k]: s[k] })}` +
        ` where slug = ${lit(slug)} and length(coalesce(summary->>'${k}', '')) < 200;`
    );
  }
}

out.push("commit;", "");
writeFileSync("supabase/ua_translations.sql", out.join("\n"));
console.log(`supabase/ua_translations.sql: ${out.length - 5} statements`);
